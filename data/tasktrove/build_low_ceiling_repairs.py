HEAVY_IMPORTS = frozenset(
    {"tensorflow", "torch", "torchvision", "cv2", "cupy", "mindspore", "pyspark"}
)
OPEN_ENDED_MATH = re.compile(
    r"(?i)\b(?:give|provide|construct|exhibit|find)\s+(?:an?\s+)?(?:example|counterexample|"
    r"some\s+integers?|all\s+(?:matrices|functions|solutions)|a\s+relation)\b"
)
KNOWN_INVALID = {
    "multifile": {
        "multifile-0144",
        "multifile-1724",
    },
    "curriculum": {
        "curriculum-medium-0126",
    },
}


def imported_roots(source: str) -> set[str]:
    tree = ast.parse(source)
    roots: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots.update(alias.name.split(".", 1)[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            roots.add(node.module.split(".", 1)[0])
    return roots


def append_instruction(source: bytes, note: str) -> bytes:
    text = source.decode("utf-8").rstrip()
    if PUBLIC_TEST_NOTE in text:
        raise ValueError("source instruction already contains the repair note")
    return f"{text}\n\n{note.strip()}\n".encode()


def public_test_note(filename: str) -> str:
    return f"""
Repair note:

- {PUBLIC_TEST_NOTE} `/setup_files/{filename}`. Copy it into `/app/` or run it
  from that path while developing. The verifier runs the same test file.
- Treat its import paths and observable assertions as part of the task contract.
"""


def repair_scaffold(
    path: str, files: dict[str, bytes]
) -> tuple[dict[str, bytes] | None, str]:
    test = files["tests/test_scaffold.py"].decode("utf-8")
    starter = files["tests/starter/scaffold.py"].decode("utf-8")
    try:
        ast.parse(test)
        ast.parse(starter)
    except SyntaxError:
        return None, "invalid_python"
    module = find_target_module(test)
    if module is None:
        return None, "no_static_target_module"
    user_roots = (
        imported_roots(test)
        - set(sys.stdlib_module_names)
        - {
            "pytest",
            "_pytest",
            "numpy",
            "pandas",
            "scipy",
            "sklearn",
            "PIL",
            "yaml",
            "click",
            "requests",
            "networkx",
            "sympy",
            "xarray",
            "h5py",
            "openpyxl",
            "bs4",
            "lxml",
            "matplotlib",
        }
    )
    if len(user_roots) > 1:
        return None, "one_scaffold_for_multiple_modules"
    if imported_roots(test) & HEAVY_IMPORTS:
        return None, "unsupported_heavy_dependency"
    target = module.replace(".", "/") + ".py"
    transformed = dict(files)
    del transformed["tests/starter/scaffold.py"]
    transformed["setup_files/starter.py"] = starter.encode()
    transformed["setup_files/test_scaffold.py"] = test.encode()
    transformed["instruction.md"] = append_instruction(
        files["instruction.md"],
        f"""
Repair note:

- The actual starter scaffold is available at `/setup_files/starter.py` before
  the agent starts. Copy it to `/app/{target}` and preserve its constants,
  signatures, type aliases, and package layout while implementing the stubs.
- {PUBLIC_TEST_NOTE} `/setup_files/test_scaffold.py`. The verifier runs the same
  test file, so its import path and observable assertions are part of the task
  contract.
""",
    )
    transformed["tests/test.sh"] = files["tests/test.sh"].replace(
        b"# Copy scaffold files as starting point\ncp /tests/starter/*.py /app/ 2>/dev/null || true\n",
        b"",
    )
    transformed["environment/Dockerfile"] = COMMON_DOCKERFILE
    return transformed, "retained"


def repair_generated_code(
    family: str, path: str, files: dict[str, bytes], test_name: str
) -> tuple[dict[str, bytes] | None, str]:
    if path in KNOWN_INVALID[family]:
        return None, "known_invalid_verifier"
    test = files[f"tests/{test_name}"].decode("utf-8")
    try:
        ast.parse(test)
    except SyntaxError:
        return None, "invalid_python"
    if imported_roots(test) & HEAVY_IMPORTS:
        return None, "unsupported_heavy_dependency"
    if "asyncio.create_task(asyncio.gather(" in test:
        return None, "invalid_asyncio_test"
    transformed = dict(files)
    transformed[f"setup_files/{test_name}"] = test.encode()
    transformed["instruction.md"] = append_instruction(
        files["instruction.md"], public_test_note(test_name)
    )
    transformed["environment/Dockerfile"] = COMMON_DOCKERFILE
    return transformed, "retained"


def repair_math(
    path: str, files: dict[str, bytes]
) -> tuple[dict[str, bytes] | None, str]:
    data = json.loads(files["tests/verifier_data.json"])
    expected = data.get("expected_answer")
    if not isinstance(expected, str):
        return None, "invalid_expected_answer"
    kind = answer_type(expected)
    instruction = files["instruction.md"].decode("utf-8")
    if kind == "text":
        return None, "unverifiable_text_answer"
    if OPEN_ENDED_MATH.search(instruction):
        return None, "multiple_valid_answers"
    transformed = dict(files)
    transformed["tests/verifier.py"] = VERIFIER_PY.encode()
    transformed["tests/verifier_data.json"] = (
        json.dumps({"expected_answer": expected, "answer_type": kind}, sort_keys=True)
        + "\n"
    ).encode()
    transformed["tests/test.sh"] = MATH_TEST_SH
    transformed["environment/Dockerfile"] = MATH_DOCKERFILE
    transformed["instruction.md"] = append_instruction(
        files["instruction.md"],
        """
Reliability note: write a provisional `/app/answer.txt` as soon as you have a
candidate answer, then refine it if needed. This preserves a scoreable answer if
later computation consumes the remaining agent time.
""",
    )
    return transformed, "retained"


def validate_task(path: str, files: dict[str, bytes]) -> None:
    missing = REQUIRED_MEMBERS - files.keys()
    if missing:
        raise ValueError(f"{path}: missing {sorted(missing)}")
    test_files = [
        name
        for name in files
        if name.startswith("tests/test_") and name.endswith(".py")
    ]
    for test_file in test_files:
        ast.parse(files[test_file].decode())


def transform_dataset(
    source: Path,
    destination: Path,
    family: str,
    source_dataset: str,
    output_dataset: str,
) -> dict[str, object]:
    parquet = pq.ParquetFile(source)
    if parquet.schema_arrow != TASK_SCHEMA:
        raise ValueError(f"unexpected schema: {parquet.schema_arrow}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    writer = pq.ParquetWriter(
        destination, TASK_SCHEMA, compression="zstd", use_dictionary=False
    )
    counts: Counter[str] = Counter()
    image_hashes: Counter[str] = Counter()
    output_rows = 0
    try:
        for batch in parquet.iter_batches(batch_size=MAX_BATCH_ROWS):
            rows = []
            for row in batch.to_pylist():
                files = read_task(row["task_binary"])
                if family == "scaffold":
                    transformed, reason = repair_scaffold(row["path"], files)
                elif family == "multifile":
                    transformed, reason = repair_generated_code(
                        family, row["path"], files, "test_multifile.py"
                    )
                elif family == "curriculum":
                    transformed, reason = repair_generated_code(
                        family, row["path"], files, "test_curriculum.py"
                    )
                elif family == "math":
                    transformed, reason = repair_math(row["path"], files)
                else:
                    raise ValueError(f"unknown family: {family}")
                counts[reason] += 1
                if transformed is None:
                    continue
                validate_task(row["path"], transformed)
                image_hashes[
                    hashlib.sha256(transformed["environment/Dockerfile"]).hexdigest()
                ] += 1
                rows.append(
                    {"path": row["path"], "task_binary": write_task(transformed)}
                )
            if rows:
                writer.write_table(pa.Table.from_pylist(rows, schema=TASK_SCHEMA))
                output_rows += len(rows)
    finally:
        writer.close()
    if output_rows < MIN_TASKS:
        raise ValueError(f"{output_dataset} fell below {MIN_TASKS} tasks")
    return {
        "source_dataset": source_dataset,
        "source_rows": parquet.metadata.num_rows,
        "source_sha256": file_sha256(source),
        "output_dataset": output_dataset,
        "output_rows": output_rows,
        "output_sha256": file_sha256(destination),
        "output": str(destination),
        "admission": dict(sorted(counts.items())),
        "image_hashes": dict(image_hashes),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sources", type=Path, required=True)
    parser.add_argument("--stage", type=Path, required=True)
    args = parser.parse_args()
    if args.stage.exists() and any(args.stage.iterdir()):
        raise ValueError(f"stage must be empty: {args.stage}")
    specifications = (
        (
            "laion__exp_rpt_scaffold-v2",
            "scaffold",
            "laion/exp_rpt_scaffold-v2",
            "laion/exp_rpt_scaffold-v3",
        ),
        (
            "DCAgent__exp_rpt_multifile-v2",
            "multifile",
            "DCAgent/exp_rpt_multifile-v2",
            "DCAgent/exp_rpt_multifile-v3",
        ),
        (
            "DCAgent__exp_rpt_curriculum-medium",
            "curriculum",
            "DCAgent/exp_rpt_curriculum-medium",
            "DCAgent/exp_rpt_curriculum-medium-v2",
        ),
        (
            "laion__nemotron-gym-math-v4",
            "math",
            "laion/nemotron-gym-math-v4",
            "laion/nemotron-gym-math-v5",
        ),
    )
    datasets = []
    for directory, family, source_dataset, output_dataset in specifications:
        destination = args.stage / output_dataset / "tasks.parquet"
        datasets.append(
            transform_dataset(
                args.sources / directory / "tasks.parquet",
                destination,
                family,
                source_dataset,
                output_dataset,
            )
        )
    image_hashes = {
        digest for dataset in datasets for digest in dataset["image_hashes"]
    }
    if len(image_hashes) > 20:
        raise ValueError(f"repair created {len(image_hashes)} images")
    retired_source = args.sources / "DCAgent__exp_rpt_curriculum-hard" / "tasks.parquet"
    retired_parquet = pq.ParquetFile(retired_source)
    manifest = {
        "source_repo": "open-thoughts/TaskTrove",
        "source_revision": SOURCE_REVISION,
        "source_version": "4.3",
        "target_version": "4.4",
        "retired_datasets": [
            {
                "source_dataset": "DCAgent/exp_rpt_curriculum-hard",
                "source_rows": retired_parquet.metadata.num_rows,
                "source_sha256": file_sha256(retired_source),
            }
        ],
        "datasets": datasets,
        "unique_images": len(image_hashes),
    }
    args.stage.mkdir(parents=True, exist_ok=True)
    (args.stage / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
